/* Generates a VAPID key pair for Web Push (P-256). Usage: node scripts/vapid.cjs [--write-env]
 * With --write-env it appends the keys to .env.local (git-ignored) unless they are already there. */
const { generateKeyPairSync } = require("crypto");
const fs = require("fs");

const { publicKey, privateKey } = generateKeyPairSync("ec", { namedCurve: "prime256v1" });
const pub = publicKey.export({ format: "jwk" });
const priv = privateKey.export({ format: "jwk" });
const b64u = (b) => Buffer.from(b).toString("base64url");
// Uncompressed EC point (0x04 || x || y), the form browsers expect as applicationServerKey.
const publicKeyB64 = b64u(Buffer.concat([Buffer.from([4]), Buffer.from(pub.x, "base64url"), Buffer.from(pub.y, "base64url")]));
const privateKeyB64 = priv.d;

if (process.argv.includes("--write-env")) {
  const file = ".env.local";
  const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (/^VAPID_PRIVATE_KEY=./m.test(cur)) {
    console.log(".env.local already has VAPID keys; left untouched.");
  } else {
    const add = `${cur.endsWith("\n") || !cur ? "" : "\n"}\n# Web Push (generated by scripts/vapid.cjs)\nNEXT_PUBLIC_VAPID_PUBLIC_KEY=${publicKeyB64}\nVAPID_PRIVATE_KEY=${privateKeyB64}\nVAPID_SUBJECT=https://pausa.gnagno.org\n`;
    fs.appendFileSync(file, add);
    console.log("VAPID keys written to .env.local.");
  }
} else {
  console.log(`NEXT_PUBLIC_VAPID_PUBLIC_KEY=${publicKeyB64}\nVAPID_PRIVATE_KEY=${privateKeyB64}`);
}
